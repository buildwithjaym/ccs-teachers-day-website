document.getElementById(
"verifyButton"
);



const input =
document.getElementById(
"accessKey"
);



const error =
document.getElementById(
"errorMessage"
);






function verifyTeacher(){



const code =
input.value.trim();




error.textContent="";




if(!code){


error.textContent =
"Please enter your access code.";


return;

}





const teacher =
teacherVault[code];






if(!teacher){


error.textContent =
"Invalid access code.";


input.value="";


return;


}







const teacherData={


code:code,


name:teacher.name,


image:teacher.image,


message:teacher.message


};






sessionStorage.setItem(
"teacher",
JSON.stringify(teacherData)
);





console.log(
"Teacher unlocked:",
teacherData
);





window.location.href =
"teacher.html";



}







verifyButton.addEventListener(
"click",
verifyTeacher
);






input.addEventListener(
"keydown",
(event)=>{


if(event.key==="Enter"){

verifyTeacher();

}


});



